create table if not exists public.tenu_players (
  character_id text primary key check (character_id in ('MMA','Ukechi','Chibaby','Doms','Jahsfavour','Mummy','Dee')),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  character_name text not null,
  appearance jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.tenu_rooms (
  room_id integer primary key check (room_id between 0 and 3),
  color text not null check (color ~ '^#[0-9a-fA-F]{6}$'),
  updated_by uuid not null references auth.users(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.tenu_chat (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  character_id text not null check (character_id in ('MMA','Ukechi','Chibaby','Doms','Jahsfavour','Mummy','Dee')),
  player_name text not null,
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.tenu_players enable row level security;
alter table public.tenu_rooms enable row level security;
alter table public.tenu_chat enable row level security;

drop policy if exists "House members can view profiles" on public.tenu_players;
create policy "House members can view profiles" on public.tenu_players
  for select to authenticated using (true);
drop policy if exists "Players can claim a profile" on public.tenu_players;
create policy "Players can claim a profile" on public.tenu_players
  for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "Players can update their profile" on public.tenu_players;
create policy "Players can update their profile" on public.tenu_players
  for update to authenticated using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
grant select, insert, update on public.tenu_players to authenticated;

create or replace function public.save_tenu_customization(
  p_character_id text,
  p_character_name text,
  p_appearance jsonb,
  p_room_color text
) returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_room_id integer;
begin
  v_room_id := case p_character_id
    when 'Dee' then 0 when 'Mummy' then 0
    when 'Ukechi' then 1 when 'Doms' then 1
    when 'Chibaby' then 2 when 'MMA' then 2
    when 'Jahsfavour' then 3
    else null
  end;
  if v_room_id is null or p_character_name !~ '.*\S.*'
     or char_length(p_character_name) > 24
     or p_room_color !~ '^#[0-9a-fA-F]{6}$' then
    raise exception 'Invalid character customization';
  end if;
  update public.tenu_players
    set character_name = p_character_name,
        appearance = p_appearance,
        updated_at = now()
    where character_id = p_character_id and user_id = (select auth.uid());
  if not found then
    raise exception 'You do not own this character profile';
  end if;
  insert into public.tenu_rooms(room_id,color,updated_by)
    values(v_room_id,p_room_color,(select auth.uid()))
  on conflict (room_id) do update
    set color = excluded.color, updated_by = excluded.updated_by, updated_at = now();
end;
$$;
grant execute on function public.save_tenu_customization(text,text,jsonb,text) to authenticated;
revoke execute on function public.save_tenu_customization(text,text,jsonb,text) from public, anon;

drop policy if exists "House members can view rooms" on public.tenu_rooms;
create policy "House members can view rooms" on public.tenu_rooms
  for select to authenticated using (true);
drop policy if exists "Roommates can create room colors" on public.tenu_rooms;
create policy "Roommates can create room colors" on public.tenu_rooms
  for insert to authenticated with check (
    updated_by = (select auth.uid()) and exists (
      select 1 from public.tenu_players p where p.user_id = (select auth.uid())
      and (
        (room_id = 0 and p.character_id in ('Mummy','Dee')) or
        (room_id = 1 and p.character_id in ('Ukechi','Doms')) or
        (room_id = 2 and p.character_id in ('Chibaby','MMA')) or
        (room_id = 3 and p.character_id = 'Jahsfavour')
      )
    )
  );
drop policy if exists "Roommates can update room colors" on public.tenu_rooms;
create policy "Roommates can update room colors" on public.tenu_rooms
  for update to authenticated using (
    exists (
      select 1 from public.tenu_players p where p.user_id = (select auth.uid())
      and (
        (room_id = 0 and p.character_id in ('Mummy','Dee')) or
        (room_id = 1 and p.character_id in ('Ukechi','Doms')) or
        (room_id = 2 and p.character_id in ('Chibaby','MMA')) or
        (room_id = 3 and p.character_id = 'Jahsfavour')
      )
    )
  ) with check (
    updated_by = (select auth.uid()) and exists (
      select 1 from public.tenu_players p where p.user_id = (select auth.uid())
      and (
        (room_id = 0 and p.character_id in ('Mummy','Dee')) or
        (room_id = 1 and p.character_id in ('Ukechi','Doms')) or
        (room_id = 2 and p.character_id in ('Chibaby','MMA')) or
        (room_id = 3 and p.character_id = 'Jahsfavour')
