    )
  );
grant select, insert, update on public.tenu_rooms to authenticated;

drop policy if exists "House members can read chat" on public.tenu_chat;
create policy "House members can read chat" on public.tenu_chat
  for select to authenticated using (true);
drop policy if exists "Players can send chat as their character" on public.tenu_chat;
create policy "Players can send chat as their character" on public.tenu_chat
  for insert to authenticated with check (
    user_id = (select auth.uid()) and exists (
      select 1 from public.tenu_players p
      where p.user_id = (select auth.uid()) and p.character_id = tenu_chat.character_id
    )
  );
grant select, insert on public.tenu_chat to authenticated;
grant usage, select on sequence public.tenu_chat_id_seq to authenticated;

do $$
declare
  v_table text;
begin
  foreach v_table in array array['tenu_chat','tenu_players','tenu_rooms'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = v_table
    ) then
      execute format('alter publication supabase_realtime add table public.%I',v_table);
    end if;
  end loop;
end $$;
