create or replace function public.complete_tenu_minigame(p_game text,p_result text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_character_id text;
  v_needs jsonb;
  v_balance bigint;
  v_coins bigint;
  v_hourly_coins bigint;
  v_last_played_at timestamptz;
begin
  if v_user_id is null
     or p_game is null
     or p_result is null
     or p_game not in ('cook','market','school')
     or p_result not in ('perfect','good','fail','auto')
     or (p_result = 'auto' and p_game <> 'cook') then
    raise exception 'Invalid mini-game result';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v_user_id::text,0));
  select p.character_id,p.needs into v_character_id,v_needs
    from public.tenu_players p where p.user_id = v_user_id for update;
  if v_character_id is null then raise exception 'Choose a household character first'; end if;

  select c.last_played_at into v_last_played_at
    from public.tenu_minigame_cooldowns c
    where c.user_id = v_user_id and c.game = p_game;
  if found and v_last_played_at > now() - interval '30 seconds' then
    raise exception 'This mini-game is cooling down';
  end if;

  v_coins := case p_game
    when 'cook' then case p_result when 'perfect' then 10 else 0 end
    when 'market' then case p_result when 'perfect' then 40 when 'good' then 20 else 0 end
    when 'school' then case p_result when 'perfect' then 50 when 'good' then 25 else 0 end
  end;
  select coalesce(sum(r.coins_awarded),0) into v_hourly_coins
    from public.tenu_minigame_results r
    where r.user_id = v_user_id and r.completed_at >= now() - interval '1 hour';
  v_coins := least(v_coins,greatest(0,100-v_hourly_coins));

  if p_game = 'cook' then
    v_needs := jsonb_set(
      coalesce(v_needs,'{"energy":100,"hunger":100,"fun":100}'::jsonb),
      '{hunger}',
      to_jsonb(least(100,coalesce((v_needs->>'hunger')::numeric,100)+case p_result
        when 'perfect' then 60 when 'good' then 40 when 'fail' then 15 else 20 end))
    );
  end if;

  insert into public.tenu_minigame_cooldowns(user_id,game,last_played_at)
    values(v_user_id,p_game,now())
    on conflict (user_id,game) do update set last_played_at = excluded.last_played_at;
  update public.tenu_players
    set needs = v_needs,updated_at = now()
    where character_id = v_character_id and user_id = v_user_id;

  select a.balance into v_balance from public.tenu_bank_accounts a
    where a.character_id = v_character_id and a.user_id = v_user_id for update;
  if not found then raise exception 'Wallet is unavailable'; end if;
  if v_coins > 0 then
    update public.tenu_bank_accounts
      set balance = balance + v_coins,updated_at = now()
      where character_id = v_character_id and user_id = v_user_id
      returning balance into v_balance;
    insert into public.tenu_game_transactions(character_id,action,amount_delta)
      values(v_character_id,'minigame',v_coins);
  end if;

  insert into public.tenu_minigame_results(user_id,character_id,game,result,coins_awarded)
    values(v_user_id,v_character_id,p_game,p_result,v_coins);
  return jsonb_build_object('coins',v_coins,'needs',v_needs,'balance',v_balance);
end;
$$;
revoke execute on function public.complete_tenu_minigame(text,text) from public, anon;
grant execute on function public.complete_tenu_minigame(text,text) to authenticated;

create or replace function public.claim_tenu_daily_goal(p_goal text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_character_id text;
  v_balance bigint;
  v_earned bigint;
  v_reward constant bigint := 150;
begin
  if p_goal is null or (select auth.uid()) is null
     or p_goal not in ('cook','nepa_bill','earn_500') then
    raise exception 'Invalid daily goal';
  end if;

  select p.character_id into v_character_id
    from public.tenu_players p where p.user_id = (select auth.uid());
  if v_character_id is null then raise exception 'Claim a household character first'; end if;

  if p_goal = 'cook' and not exists (
    select 1 from public.tenu_minigame_results r
    where r.character_id = v_character_id and r.game = 'cook'
      and r.completed_at >= current_date
  ) then
    raise exception 'Complete a cooking mini-game before claiming this goal';
  end if;

  if p_goal = 'nepa_bill' and not exists (
    select 1 from public.tenu_game_transactions t
    where t.character_id = v_character_id and t.action = 'bill'
      and t.amount_delta < 0 and t.created_at >= current_date
  ) then
    raise exception 'Pay the NEPA bill before claiming this goal';
  end if;

  if p_goal = 'earn_500' then
    select coalesce(sum(t.amount_delta),0) into v_earned
      from public.tenu_game_transactions t
      where t.character_id = v_character_id and t.action in ('work','school','market','minigame')
        and t.amount_delta > 0 and t.created_at >= current_date;
    if v_earned < 500 then raise exception 'Earn 500 coins before claiming this goal'; end if;
  end if;

  select a.balance into v_balance from public.tenu_bank_accounts a
    where a.character_id = v_character_id and a.user_id = (select auth.uid()) for update;
  if not found then raise exception 'Wallet is unavailable'; end if;

  insert into public.tenu_daily_goals(character_id,action_date,goal,reward)
    values(v_character_id,current_date,p_goal,v_reward) on conflict do nothing;
  if not found then return 0; end if;

  update public.tenu_bank_accounts
    set balance = balance + v_reward, updated_at = now()
    where character_id = v_character_id and user_id = (select auth.uid());
  if not found then raise exception 'Wallet is unavailable'; end if;
  insert into public.tenu_game_transactions(character_id,action,amount_delta)
    values(v_character_id,'daily_goal',v_reward);
  return v_reward;
end;
$$;
revoke execute on function public.claim_tenu_daily_goal(text) from public, anon;
grant execute on function public.claim_tenu_daily_goal(text) to authenticated;
