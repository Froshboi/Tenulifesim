  add constraint tenu_game_transactions_action_check
  check (action in (
    'work','school','market','groceries','outfit','phone','bill','doms_gift',
    'diesel','daily_goal','bolt','uber','keke','flight_abuja',
    'flight_port_harcourt','flight_enugu','build_item','sell_item','minigame'
  ));

create table if not exists public.tenu_minigame_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  character_id text not null references public.tenu_players(character_id) on update cascade on delete cascade,
  game text not null check (game in ('cook','market','school')),
  result text not null check (result in ('perfect','good','fail','auto')),
  coins_awarded bigint not null check (coins_awarded >= 0),
  completed_at timestamptz not null default now()
);

create index if not exists tenu_minigame_results_user_completed
  on public.tenu_minigame_results(user_id,completed_at desc);

create table if not exists public.tenu_minigame_cooldowns (
  user_id uuid not null references auth.users(id) on delete cascade,
  game text not null check (game in ('cook','market','school')),
  last_played_at timestamptz not null,
  primary key (user_id,game)
);

alter table public.tenu_minigame_results enable row level security;
alter table public.tenu_minigame_cooldowns enable row level security;
revoke all on public.tenu_minigame_results from public, anon, authenticated;
