alter table public.tenu_players
  add column if not exists needs jsonb not null
    default '{"energy":100,"hunger":100,"fun":100}'::jsonb;

create table if not exists public.tenu_daily_actions (
  character_id text not null references public.tenu_players(character_id) on update cascade on delete cascade,
  action_date date not null default current_date,
  action text not null check (action in ('work','school','market','doms_gift')),
  created_at timestamptz not null default now(),
  primary key (character_id,action_date,action)
);

create table if not exists public.tenu_game_transactions (
  id bigint generated by default as identity primary key,
  character_id text not null references public.tenu_players(character_id) on update cascade on delete cascade,
  action text not null check (action in ('work','school','market','groceries','outfit','phone','bill','doms_gift')),
  amount_delta bigint not null check (amount_delta <> 0),
  created_at timestamptz not null default now()
);

alter table public.tenu_daily_actions enable row level security;
alter table public.tenu_game_transactions enable row level security;
revoke all on public.tenu_daily_actions from public, anon, authenticated;
revoke insert, update, delete, truncate, references, trigger on public.tenu_game_transactions from public, anon, authenticated;
grant select on public.tenu_game_transactions to authenticated;
drop policy if exists "Players can read their game transactions" on public.tenu_game_transactions;
create policy "Players can read their game transactions" on public.tenu_game_transactions
  for select to authenticated using (exists (
    select 1 from public.tenu_players p
    where p.character_id = tenu_game_transactions.character_id
      and p.user_id = (select auth.uid())
  ));

create or replace function public.save_tenu_needs(
  p_character_id text,
  p_needs jsonb
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_energy numeric;
  v_hunger numeric;
  v_fun numeric;
begin
  if (p_needs is null
     or (select auth.uid()) is null
     or jsonb_typeof(p_needs) <> 'object'
     or not exists (
       select 1 from public.tenu_players p
       where p.character_id = p_character_id and p.user_id = (select auth.uid())
     )) then
    raise exception 'Invalid needs update';
  end if;
  begin
    v_energy := (p_needs->>'energy')::numeric;
    v_hunger := (p_needs->>'hunger')::numeric;
    v_fun := (p_needs->>'fun')::numeric;
  exception when invalid_text_representation or numeric_value_out_of_range then
    raise exception 'Needs must be numeric values';
  end;
  if v_energy is null or v_hunger is null or v_fun is null
     or v_energy not between 0 and 100
     or v_hunger not between 0 and 100
     or v_fun not between 0 and 100 then
    raise exception 'Needs must be between 0 and 100';
  end if;
  update public.tenu_players
    set needs = jsonb_build_object('energy',v_energy,'hunger',v_hunger,'fun',v_fun),
        updated_at = now()
    where character_id = p_character_id and user_id = (select auth.uid());
end;
$$;
revoke execute on function public.save_tenu_needs(text,jsonb) from public, anon;
grant execute on function public.save_tenu_needs(text,jsonb) to authenticated;

create or replace function public.earn_tenu_activity(p_activity text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_character_id text;
  v_amount bigint;
  v_balance bigint;
begin
  if (select auth.uid()) is null or p_activity is null or p_activity not in ('work','school','market') then
    raise exception 'Invalid activity';
  end if;
  select p.character_id into v_character_id
    from public.tenu_players p where p.user_id = (select auth.uid());
  if v_character_id is null then raise exception 'Claim a household character first'; end if;
  v_amount := case p_activity when 'work' then 400 when 'school' then 100 else 300 end;
  insert into public.tenu_daily_actions(character_id,action)
    values(v_character_id,p_activity) on conflict do nothing;
  if not found then return 0; end if;
  select a.balance into v_balance from public.tenu_bank_accounts a
    where a.character_id = v_character_id and a.user_id = (select auth.uid()) for update;
  if not found then raise exception 'Wallet is unavailable'; end if;
  update public.tenu_bank_accounts
    set balance = balance + v_amount, updated_at = now()
    where character_id = v_character_id;
  insert into public.tenu_game_transactions(character_id,action,amount_delta)
    values(v_character_id,p_activity,v_amount);
  return v_amount;
end;
$$;
revoke execute on function public.earn_tenu_activity(text) from public, anon;
grant execute on function public.earn_tenu_activity(text) to authenticated;

create or replace function public.purchase_tenu_item(p_item text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_character_id text;
  v_price bigint;
  v_balance bigint;
begin
  if (select auth.uid()) is null then raise exception 'Sign in to shop'; end if;
  v_price := case p_item
    when 'groceries' then 120 when 'outfit' then 350
    when 'phone' then 900 when 'bill' then 250 else null
  end;
  if v_price is null then raise exception 'Unknown shop item'; end if;
  select p.character_id into v_character_id
    from public.tenu_players p where p.user_id = (select auth.uid());
  if v_character_id is null then raise exception 'Claim a household character first'; end if;
  select a.balance into v_balance from public.tenu_bank_accounts a
    where a.character_id = v_character_id and a.user_id = (select auth.uid()) for update;
  if not found or v_balance < v_price then raise exception 'Insufficient balance'; end if;
  update public.tenu_bank_accounts
    set balance = balance - v_price, updated_at = now()
    where character_id = v_character_id;
  if p_item = 'groceries' then
    update public.tenu_players
      set needs = jsonb_set(needs,'{hunger}','100'::jsonb,true), updated_at = now()
      where character_id = v_character_id;
  end if;
  insert into public.tenu_game_transactions(character_id,action,amount_delta)
    values(v_character_id,p_item,-v_price);
  return v_balance - v_price;
end;
$$;
revoke execute on function public.purchase_tenu_item(text) from public, anon;
grant execute on function public.purchase_tenu_item(text) to authenticated;

create or replace function public.doms_random_gift(p_to_character_id text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_amount bigint;
  v_balance bigint;
begin
  if (select auth.uid()) is null
     or not exists (
       select 1 from public.tenu_players p
       where p.character_id = 'Doms' and p.user_id = (select auth.uid())
     ) then
    raise exception 'Only Doms can send this gift';
  end if;
  if p_to_character_id = 'Doms' or not exists (
    select 1 from public.tenu_bank_accounts a where a.character_id = p_to_character_id
  ) then
    raise exception 'Choose another claimed household character';
  end if;
  insert into public.tenu_daily_actions(character_id,action)
    values('Doms','doms_gift') on conflict do nothing;
  if not found then return 0; end if;
  if random() >= 0.35 then return 0; end if;
  v_amount := 100 + floor(random()*401)::bigint;
  perform a.character_id from public.tenu_bank_accounts a
    where a.character_id in ('Doms',p_to_character_id)
    order by a.character_id for update;
  select a.balance into v_balance from public.tenu_bank_accounts a
    where a.character_id = 'Doms' and a.user_id = (select auth.uid());
  if v_balance is null or v_balance < v_amount then raise exception 'Insufficient balance'; end if;
  update public.tenu_bank_accounts
    set balance = balance - v_amount, updated_at = now()
    where character_id = 'Doms' and user_id = (select auth.uid());
  update public.tenu_bank_accounts
    set balance = balance + v_amount, updated_at = now()
    where character_id = p_to_character_id;
  insert into public.tenu_game_transactions(character_id,action,amount_delta)
    values('Doms','doms_gift',-v_amount),(p_to_character_id,'doms_gift',v_amount);
  return v_amount;
end;
$$;
revoke execute on function public.doms_random_gift(text) from public, anon;
grant execute on function public.doms_random_gift(text) to authenticated;
