create table if not exists public.tenu_bank_accounts (
  character_id text primary key references public.tenu_players(character_id) on update cascade on delete cascade,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  balance bigint not null default 10000 check (balance between 0 and 9000000000000000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tenu_bank_transfers (
  id uuid primary key,
  from_character_id text not null,
  to_character_id text not null,
  amount bigint not null check (amount between 1 and 10000),
  initiated_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  check (from_character_id <> to_character_id)
);

create table if not exists public.tenu_bank_ledger (
  id bigint generated by default as identity primary key,
  character_id text not null,
  entry_type text not null check (entry_type in ('opening','debit','credit')),
  amount_delta bigint not null check (amount_delta <> 0),
  transfer_id uuid references public.tenu_bank_transfers(id),
  created_at timestamptz not null default now()
);
create unique index if not exists tenu_bank_one_opening_entry
  on public.tenu_bank_ledger(character_id) where entry_type = 'opening';

alter table public.tenu_bank_accounts enable row level security;
alter table public.tenu_bank_transfers enable row level security;
alter table public.tenu_bank_ledger enable row level security;

drop policy if exists "Players can read their wallet" on public.tenu_bank_accounts;
create policy "Players can read their wallet" on public.tenu_bank_accounts
  for select to authenticated using (user_id = (select auth.uid()));
grant select on public.tenu_bank_accounts to authenticated;
revoke insert, update, delete, truncate, references, trigger on public.tenu_bank_accounts from public, anon, authenticated;

drop policy if exists "Players can read their transfers" on public.tenu_bank_transfers;
create policy "Players can read their transfers" on public.tenu_bank_transfers
  for select to authenticated using (
    initiated_by = (select auth.uid()) or exists (
      select 1 from public.tenu_bank_accounts a
      where a.character_id = tenu_bank_transfers.to_character_id
        and a.user_id = (select auth.uid())
    )
  );
grant select on public.tenu_bank_transfers to authenticated;
revoke insert, update, delete, truncate, references, trigger on public.tenu_bank_transfers from public, anon, authenticated;

drop policy if exists "Players can read their ledger" on public.tenu_bank_ledger;
create policy "Players can read their ledger" on public.tenu_bank_ledger
  for select to authenticated using (exists (
    select 1 from public.tenu_bank_accounts a
    where a.character_id = tenu_bank_ledger.character_id
      and a.user_id = (select auth.uid())
  ));
grant select on public.tenu_bank_ledger to authenticated;
revoke insert, update, delete, truncate, references, trigger on public.tenu_bank_ledger from public, anon, authenticated;

create or replace function public.create_tenu_wallet()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.tenu_bank_accounts(character_id,user_id,balance)
    values(new.character_id,new.user_id,10000)
  on conflict (character_id) do update
    set user_id = excluded.user_id;
  if tg_op = 'INSERT' then
    insert into public.tenu_bank_ledger(character_id,entry_type,amount_delta)
      values(new.character_id,'opening',10000)
      on conflict do nothing;
  end if;
  return new;
end;
$$;
revoke execute on function public.create_tenu_wallet() from public, anon, authenticated;

drop trigger if exists tenu_player_wallet on public.tenu_players;
create trigger tenu_player_wallet
  after insert or update of character_id,user_id on public.tenu_players
  for each row execute function public.create_tenu_wallet();

insert into public.tenu_bank_accounts(character_id,user_id)
  select character_id,user_id from public.tenu_players
  on conflict (character_id) do nothing;
insert into public.tenu_bank_ledger(character_id,entry_type,amount_delta)
  select a.character_id,'opening',a.balance
  from public.tenu_bank_accounts a
  where not exists (
    select 1 from public.tenu_bank_ledger l
    where l.character_id = a.character_id and l.entry_type = 'opening'
  );

create or replace function public.transfer_tenu_coins(
  p_transfer_id uuid,
  p_from_character_id text,
  p_to_character_id text,
  p_amount bigint
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existing public.tenu_bank_transfers%rowtype;
begin
  if (select auth.uid()) is null
     or p_transfer_id is null
     or p_from_character_id = p_to_character_id
     or p_amount not between 1 and 10000 then
    raise exception 'Invalid transfer request';
  end if;

  if not exists (
    select 1 from public.tenu_players p
    where p.character_id = p_from_character_id and p.user_id = (select auth.uid())
  ) then
    raise exception 'You do not own the sending character';
  end if;
  if not exists (
    select 1 from public.tenu_bank_accounts a
    where a.character_id = p_to_character_id
  ) then
    raise exception 'Recipient must claim a household character first';
  end if;
  perform a.character_id from public.tenu_bank_accounts a
    where a.character_id in (p_from_character_id,p_to_character_id)
    order by a.character_id for update;

  insert into public.tenu_bank_transfers(id,from_character_id,to_character_id,amount,initiated_by)
    values(p_transfer_id,p_from_character_id,p_to_character_id,p_amount,(select auth.uid()))
    on conflict (id) do nothing;
  if not found then
    select * into v_existing from public.tenu_bank_transfers where id = p_transfer_id;
    if v_existing.initiated_by = (select auth.uid())
       and v_existing.from_character_id = p_from_character_id
       and v_existing.to_character_id = p_to_character_id
       and v_existing.amount = p_amount then
      return;
    end if;
    raise exception 'Transfer request ID has already been used';
  end if;

  update public.tenu_bank_accounts
    set balance = balance - p_amount, updated_at = now()
    where character_id = p_from_character_id
      and user_id = (select auth.uid())
      and balance >= p_amount;
  if not found then
    raise exception 'Insufficient balance';
  end if;

  update public.tenu_bank_accounts
    set balance = balance + p_amount, updated_at = now()
    where character_id = p_to_character_id;
  if not found then
    raise exception 'Recipient wallet is unavailable';
  end if;

  insert into public.tenu_bank_ledger(character_id,entry_type,amount_delta,transfer_id)
    values
      (p_from_character_id,'debit',-p_amount,p_transfer_id),
      (p_to_character_id,'credit',p_amount,p_transfer_id);
end;
$$;
revoke execute on function public.transfer_tenu_coins(uuid,text,text,bigint) from public, anon;
grant execute on function public.transfer_tenu_coins(uuid,text,text,bigint) to authenticated;
